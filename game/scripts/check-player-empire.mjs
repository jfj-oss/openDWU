#!/usr/bin/env node
// Multiplayer guard (docs/MULTIPLAYER.md): src/sim must not grow new reads of `playerEmpire` (galaxy.playerEmpire, the
// single-player alias). Sim rules about humans ask isHumanEmpire / humanEmpires (src/sim/humanEmpires.ts); what one
// screen shows is the local viewer (src/localViewer.ts, main thread only).
//
//   npm run check:player-empire              exit 1 when a file of src/sim has more playerEmpire code lines than
//                                            scripts/player-empire-allowlist.json allows (or is new to it)
//   npm run check:player-empire -- --update  rewrite the allow-list from the current tree (after a migration)
//
// Counted: lines of src/sim/**/*.ts naming `playerEmpire` as a word, outside // and /* */ comment lines. Fewer lines
// than allowed is fine (the check prints a reminder to --update).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const simDir = join(root, 'src', 'sim');
const listFile = join(root, 'scripts', 'player-empire-allowlist.json');

function walk(dir, out = []) {
    for (const name of readdirSync(dir)) {
        const p = join(dir, name);
        if (statSync(p).isDirectory()) walk(p, out);
        else if (name.endsWith('.ts')) out.push(p);
    }
    return out;
}

function count(text) {
    let n = 0;
    for (const line of text.split('\n')) {
        const t = line.trim();
        if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) continue;
        if (/\bplayerEmpire\b/.test(line)) n++;
    }
    return n;
}

const counts = {};
for (const f of walk(simDir).sort()) {
    const n = count(readFileSync(f, 'utf8'));
    if (n > 0) counts[relative(root, f).split('\\').join('/')] = n;
}

if (process.argv.includes('--update')) {
    writeFileSync(listFile, `${JSON.stringify({ note: 'Generated by scripts/check-player-empire.mjs --update: playerEmpire code lines allowed per src/sim file.', files: counts }, null, 2)}\n`);
    console.log(`[check:player-empire] allow-list written: ${Object.keys(counts).length} files, ${Object.values(counts).reduce((a, b) => a + b, 0)} lines`);
    process.exit(0);
}

const allowed = JSON.parse(readFileSync(listFile, 'utf8')).files;
let bad = 0;
let shrunk = 0;
for (const [f, n] of Object.entries(counts)) {
    const max = allowed[f] ?? 0;
    if (n > max) {
        console.error(`[check:player-empire] ${f}: ${n} playerEmpire lines, ${max} allowed — use isHumanEmpire / humanEmpires (src/sim/humanEmpires.ts)`);
        bad++;
    } else if (n < max) shrunk++;
}
for (const f of Object.keys(allowed)) if (counts[f] === undefined) shrunk++;
if (bad > 0) process.exit(1);
console.log(`[check:player-empire] ok${shrunk > 0 ? ` (${shrunk} file(s) below the allow-list: run with --update)` : ''}`);
