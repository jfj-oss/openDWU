/** Galaxy.2.cs ResolveDescription(<enum> member) for the C# member name `name` (undefined: not a member). */
export function resolveEnumTextDescription(table: EnumText, name: string | undefined): string {
    if (name !== undefined) {
        const tag = table.tags[name];
        if (tag !== undefined) return isTextLoaded() ? getText(tag) : tag;
        if (table.fallback === 'split') return splitString(name);
    }
    // switch statement without a case: `string result = string.Empty`; out-of-range value in a switch expression:
    // SplitString(value.ToString()) of a number has no capitals -> "".
    return '';
}
