// Port of the Galaxy.2.cs ResolveDescription(enum) overloads that empire / event message texts use: each maps an enum
// member to TextResolver.GetText(<GameText.txt tag>); members without a case fall back to string.Empty (switch
// statements) or SplitString(member.ToString()) (switch expressions with `_ => SplitString(...)`). The tables below are
// the C# cases verbatim (tag strings as in the C# source; every tag is in GameText.txt).
//
// Like the C#, the result is the resolved text (callers ToLower it or format it into another message). Without a loaded
// GameText table (headless tests without game data) the tag itself is returned.

import { getText, isTextLoaded } from './textResolver';
import { splitString } from './data/gameText';

export interface EnumText {
    fallback: 'empty' | 'split';
    tags: Readonly<Record<string, string>>;
}

