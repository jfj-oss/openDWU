/** stars/star_blackhole_0.png (bitmap_199[0] → texture2D_12[0]). */
export const BLACK_HOLE_LAYER_URL = `${IMG}/stars/star_blackhole_0.png`;

/** stars/blackhole/BlkHole-0001 … 0100.png (bitmap_200, Main.Part13.cs 1144-1162: fixed names, 1-based). */
export function blackHoleFrameUrls(): string[] {
    const urls: string[] = [];
    for (let i = 1; i <= 100; i++) urls.push(`${IMG}/stars/blackhole/BlkHole-${String(i).padStart(4, '0')}.png`);
    return urls;
}

/** MainView.1.cs 657-680: the three layer tints [color_3 (inner), color_4 (middle), color_5 (outer)] by HabitatIndex % 4. */
export function blackHoleTints(habitatIndex: number): [number, number, number] {
    switch (((habitatIndex % 4) + 4) % 4) {
        case 0:
            return [0x0000d8, 0x00008a, 0x000070];
        case 1:
            return [0x54368a, 0x381e54, 0x30143c];
        case 2:
            return [0x362054, 0x26183c, 0x201430];
        default:
            return [0x541e60, 0x3e1448, 0x381040];
    }
}

/** One layer of the system-zoom black hole: size as a fraction of the drawn star, rotation = double_4 / divisor. */
export interface BlackHoleLayer {
    scale: number;
    divisor: number;
    /** Index into blackHoleTints' result. */
    tint: 0 | 1 | 2;
}

/** MainView.1.cs 690-716, in draw order (outer first). */
export const BLACK_HOLE_LAYERS: readonly BlackHoleLayer[] = [
    { scale: 1.0, divisor: 5.3, tint: 2 },
    { scale: 0.44, divisor: 2.3, tint: 1 },
    { scale: 0.2, divisor: 1, tint: 0 },
];
/** MainView.1.cs 717-721: the accretion animation's size factor and frame rate. */
export const BLACK_HOLE_FRAME_SCALE = 0.08;
export const BLACK_HOLE_FPS = 15;
/** MainView.1.cs 651: double_4 grows by 0.4 per second of Galaxy.CurrentDateTime. */
export const BLACK_HOLE_SPIN_PER_SECOND = 0.4;
/** The system pass draws habitats only while f < 500 (MainView.1.cs 436). */
export const SYSTEM_PASS_MAX_FACTOR = 500;

/** double_4 at game time `gameMs` (the C# accumulates the same game-time deltas). */
export function blackHoleSpin(gameMs: number): number {
    return (gameMs / 1000) * BLACK_HOLE_SPIN_PER_SECOND;
}

/** (int)(drawn * factor): a layer's px size (MainView.1.cs 686-718). */
export function blackHoleLayerPx(drawnPx: number, scale: number): number {
    return Math.trunc(drawnPx * scale);
}

/**
 * The galaxy-pass black hole picture's side in px (MainView.2.cs 5337-5374, 5476-5486): val3 =
 * (int)(max(MaxSolarSystemSize, TSV radius) / f), (int)(val3 * 2.0), at least 5, clamped to 11..17 below f 5100;
 * the square is 2 * val3.
 */
export function blackHoleGalaxyPx(f: number, systemRadius: number): number {
    let val3 = Math.trunc(systemRadius / f);
    val3 = Math.trunc(val3 * 2.0);
    val3 = Math.max(5, val3);
    if (f < 5100) val3 = Math.min(17, Math.max(11, val3));
    return val3 * 2;
}

/** The C# system radius (MainView.2.cs 5235-5338): max(MaxSolarSystemSize, min(TSV, 1500000)^0.35 * 600). */
export function systemPassRadius(totalStrategicValue: number, maxSolarSystemSize: number): number {
    const tsv = Math.min(Math.max(0, totalStrategicValue), 1500000);
    return Math.max(maxSolarSystemSize, Math.pow(tsv, 0.35) * 600.0);
}

/**
 * The shared black-hole art: the layer texture and the 100 accretion frames, each cropped by 10 % of its width on
 * every side and scaled to 100 x 100 (method_24 + PrecacheScaledBitmap), packed into one 1000 x 1000 atlas (one GPU
 * texture instead of a hundred 360 px ones). Loaded on first use.
 */
export class BlackHoleArt {
    layer: Texture = Texture.EMPTY;
    frames: Texture[] = [];
    private loading: Promise<void> | null = null;

    constructor(
        private readonly loadTexture: (url: string) => Promise<Texture>,
        private readonly loadImage: (url: string) => Promise<ImageBitmap | null>,
    ) {}

    get ready(): boolean {
        return this.frames.length > 0;
    }

    load(): Promise<void> {
        if (this.loading !== null) return this.loading;
        this.loading = (async () => {
            const [layer, images] = await Promise.all([this.loadTexture(BLACK_HOLE_LAYER_URL), Promise.all(blackHoleFrameUrls().map((u) => this.loadImage(u)))]);
            this.layer = layer;
            const cell = 100;
            const { canvas, ctx } = makeTextureCanvas(cell * 10, cell * 10);
            ctx.imageSmoothingEnabled = true;
            ctx.imageSmoothingQuality = 'high';
            const present: number[] = [];
            images.forEach((img, i) => {
                if (img === null) return;
                const crop = Math.trunc(img.width * 0.1);
                ctx.drawImage(img, crop, crop, img.width - crop * 2, img.height - crop * 2, (i % 10) * cell, Math.trunc(i / 10) * cell, cell, cell);
                img.close();
                present.push(i);
            });
            if (present.length === 0) {
                this.frames = [Texture.EMPTY];
                return;
            }
            const atlas = textureFromCanvas(canvas, 'blackhole-frames');
            useMinifyingFilter(atlas);
            // A missing frame keeps the previous one (the C# would have thrown; a partial install should still animate).
            const frames: Texture[] = [];
            let last = present[0];
            for (let i = 0; i < 100; i++) {
                if (images[i] !== null) last = i;
                frames.push(new Texture({ source: atlas.source, frame: new Rectangle((last % 10) * cell, Math.trunc(last / 10) * cell, cell, cell) }));
            }
            this.frames = frames;
        })();
        return this.loading;
    }
}

/** The system-zoom black hole of one system: three tinted rotating layers and the accretion animation. */
export class BlackHoleView {
    readonly root = new Container();
    private readonly layers: Sprite[] = [];
    private readonly accretion = new Sprite(Texture.EMPTY);
    private readonly tints: [number, number, number];

    constructor(habitatIndex: number, private readonly art: BlackHoleArt) {
        this.tints = blackHoleTints(habitatIndex);
        for (const l of BLACK_HOLE_LAYERS) {
            const s = new Sprite(Texture.EMPTY);
            s.anchor.set(0.5);
            s.tint = this.tints[l.tint];
            this.layers.push(s);
            this.root.addChild(s);
        }
        this.accretion.anchor.set(0.5);
        this.root.addChild(this.accretion);
        this.root.visible = false;
    }

    /** Per frame: `drawnPx` = max(4, Diameter / f), `gameMs` = the render-interpolated game clock. */
    update(show: boolean, drawnPx: number, z: number, gameMs: number, coronaFrameIndex: (nowMs: number, n: number, fps: number) => number): void {
        if (!show) {
            this.root.visible = false;
            return;
        }
        if (!this.art.ready) {
            void this.art.load();
            this.root.visible = false;
            return;
        }
        this.root.visible = true;
        const spin = blackHoleSpin(gameMs);
        for (let i = 0; i < BLACK_HOLE_LAYERS.length; i++) {
            const l = BLACK_HOLE_LAYERS[i];
            const s = this.layers[i];
            if (s.texture !== this.art.layer) s.texture = this.art.layer;
            const px = blackHoleLayerPx(drawnPx, l.scale);
            s.visible = px > 0 && s.texture.width > 1;
            if (!s.visible) continue;
            s.scale.set(px / (s.texture.width * z));
            s.rotation = spin / l.divisor;
        }
        const fpx = blackHoleLayerPx(drawnPx, BLACK_HOLE_FRAME_SCALE);
        this.accretion.visible = fpx > 0;
        if (this.accretion.visible) {
            this.accretion.texture = this.art.frames[coronaFrameIndex(gameMs, this.art.frames.length, BLACK_HOLE_FPS)] ?? this.art.frames[0];
            this.accretion.scale.set(fpx / (this.accretion.texture.width * z));
        }
    }
}

