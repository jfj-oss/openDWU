/** A source rectangle in bitmap pixels. */
export interface PxRect {
    x: number;
    y: number;
    w: number;
    h: number;
}

/** method_146 1st half: the up-scale for a source region `srcW` px wide, min(10, 400 / srcW), at least 1. */
export function gasCloudDetailScale(srcW: number): number {
    if (srcW <= 0) return 10;
    const val = Math.min(10.0, 400 / srcW);
    return val > 1.0 ? val : 1.0;
}

/**
 * MainView.1.cs method_136 / 137-143: the visible part of the cloud in bitmap px (the screen ∩ the cloud rect), or
 * null when the cloud is off screen. `view` is the camera's world rect.
 */
export function gasCloudVisibleRect(cloud: Pick<Habitat, 'xpos' | 'ypos' | 'diameter'>, bmpW: number, bmpH: number, view: PxRect): PxRect | null {
    const w = cloud.diameter;
    const h = (cloud.diameter * bmpH) / bmpW;
    const left = cloud.xpos - w / 2;
    const top = cloud.ypos - h / 2;
    const x0 = Math.max(left, view.x);
    const y0 = Math.max(top, view.y);
    const x1 = Math.min(left + w, view.x + view.w);
    const y1 = Math.min(top + h, view.y + view.h);
    if (x1 <= x0 || y1 <= y0) return null;
    const s = bmpW / w;
    return { x: (x0 - left) * s, y: (y0 - top) * s, w: (x1 - x0) * s, h: (y1 - y0) * s };
}

/** method_123: inflate a rect by `factor` about its centre. */
export function inflateRect(r: PxRect, factor: number): PxRect {
    const w = r.w * factor;
    const h = r.h * factor;
    return { x: r.x - (w - r.w) / 2, y: r.y - (h - r.h) / 2, w, h };
}

/** method_143: clip a rect to the bitmap. */
export function clipRect(r: PxRect, bmpW: number, bmpH: number): PxRect {
    let { x, y, w, h } = r;
    if (x + w >= bmpW) w -= x + w - bmpW;
    if (y + h >= bmpH) h -= y + h - bmpH;
    if (x < 0) {
        w += x;
        x = 0;
    }
    if (y < 0) {
        h += y;
        y = 0;
    }
    return { x, y, w, h };
}

export function rectContains(outer: PxRect, inner: PxRect): boolean {
    return inner.x >= outer.x && inner.y >= outer.y && inner.x + inner.w <= outer.x + outer.w && inner.y + inner.h <= outer.y + outer.h;
}

/**
 * Port of MainView.2.cs method_146 (bool_13 transparent, float_0 0.1, float_1 10) for `src` (bitmap px) of `base`:
 * the region scaled by `scale` (output at most 2000 px a side; the C# draws it with HighQualityBicubic, here bilinear
 * on premultiplied samples), then SectorCloudGenerator.FbmImageTransparent — every pixel with alpha keeps
 * (int)(A * (fBm(u, v, 6) + 1) / 2), u / v starting at src.x / src.y * 10 / base.width and stepping
 * 10 / (base.width * scale) per output pixel. Rows [row0, row1) of the output only (the caller time-slices).
 */
export function renderGasCloudDetailRows(base: RgbaImage, src: PxRect, scale: number, fractal: CFractal, out: Uint8ClampedArray, outW: number, row0: number, row1: number): void {
    const bw = base.width;
    const bh = base.height;
    const img = base.image;
    const startU = (src.x * 10) / bw;
    const startV = (src.y * 10) / bw;
    const skip = 10 / (bw * scale);
    for (let y = row0; y < row1; y++) {
        const sy = src.y + (y + 0.5) / scale - 0.5;
        const y0 = Math.max(0, Math.min(bh - 1, Math.floor(sy)));
        const y1 = Math.min(bh - 1, y0 + 1);
        const ty = Math.max(0, Math.min(1, sy - Math.floor(sy)));
        const v = startV + y * skip;
        let o = y * outW * 4;
        for (let x = 0; x < outW; x++, o += 4) {
            const sx = src.x + (x + 0.5) / scale - 0.5;
            const x0 = Math.max(0, Math.min(bw - 1, Math.floor(sx)));
            const x1 = Math.min(bw - 1, x0 + 1);
            const tx = Math.max(0, Math.min(1, sx - Math.floor(sx)));
            const i00 = (y0 * bw + x0) * 4;
            const i10 = (y0 * bw + x1) * 4;
            const i01 = (y1 * bw + x0) * 4;
            const i11 = (y1 * bw + x1) * 4;
            const w00 = (1 - tx) * (1 - ty);
            const w10 = tx * (1 - ty);
            const w01 = (1 - tx) * ty;
            const w11 = tx * ty;
            const a00 = img[i00 + 3] * w00;
            const a10 = img[i10 + 3] * w10;
            const a01 = img[i01 + 3] * w01;
            const a11 = img[i11 + 3] * w11;
            const a = a00 + a10 + a01 + a11;
            if (a < 0.5) {
                out[o + 3] = 0;
                continue;
            }
            const r = (img[i00] * a00 + img[i10] * a10 + img[i01] * a01 + img[i11] * a11) / a;
            const g = (img[i00 + 1] * a00 + img[i10 + 1] * a10 + img[i01 + 1] * a01 + img[i11 + 1] * a11) / a;
            const b = (img[i00 + 2] * a00 + img[i10 + 2] * a10 + img[i01 + 2] * a01 + img[i11 + 2] * a11) / a;
            const n = fractal.fBm(startU + x * skip, v, 6);
            out[o] = r;
            out[o + 1] = g;
            out[o + 2] = b;
            out[o + 3] = Math.trunc(Math.trunc(a) * ((n + 1) / 2));
        }
    }
}

/** method_146's output size for `src` at `scale` (each side at least 1, at most 2000). */
export function gasCloudDetailSize(src: PxRect, scale: number): { w: number; h: number } {
    return { w: Math.min(2000, Math.max(1, Math.trunc(src.w * scale))), h: Math.min(2000, Math.max(1, Math.trunc(src.h * scale))) };
}

/** A time-sliced method_146 render: call step() until it returns a texture. */
export class GasCloudDetailJob {
    readonly size: { w: number; h: number };
    private readonly out: Uint8ClampedArray;
    private row = 0;
    constructor(
        private readonly base: RgbaImage,
        readonly src: PxRect,
        readonly scale: number,
        private readonly fractal: CFractal,
    ) {
        this.size = gasCloudDetailSize(src, scale);
        this.out = new Uint8ClampedArray(this.size.w * this.size.h * 4);
    }
    get done(): boolean {
        return this.row >= this.size.h;
    }
    /** Render rows until `budgetMs` is spent; the finished texture once the last row is done, else null. */
    step(budgetMs: number, now: () => number = () => performance.now()): Texture | null {
        const t0 = now();
        while (this.row < this.size.h) {
            const next = Math.min(this.size.h, this.row + 8);
            renderGasCloudDetailRows(this.base, this.src, this.scale, this.fractal, this.out, this.size.w, this.row, next);
            this.row = next;
            if (now() - t0 >= budgetMs) break;
        }
        if (this.row < this.size.h) return null;
        const tex = textureFromRgbaPixels(this.out, this.size.w, this.size.h, false, 'gascloud-detail');
        useMinifyingFilter(tex);
        return tex;
    }
}

/** The pixel stats a test or a screenshot report wants of a generated cloud. */
export function opaqueShare(img: RgbaImage): number {
    let n = 0;
    for (let i = 3; i < img.image.length; i += 4) if (img.image[i] > 0) n++;
    return n / (img.width * img.height);
}

/** Per-frame work allowance shared by every gas cloud (reset by the Main View each frame). */
export interface GasCloudFrameBudget {
    /** Milliseconds of time-sliced method_146 rendering left this frame. */
    ms: number;
    /** Whole-bitmap generations (GenerateNebulaBackdrop, not sliceable) left this frame. */
    generations: number;
}

/** Generated gas clouds (base bitmap + whole-cloud texture) kept at once; older ones are rebuilt on demand. */
export const GAS_CLOUD_CACHE_LIMIT = 16;
/** A magnified patch is rendered once the C# scale exceeds the whole-cloud texture's by this factor. */
const PATCH_SCALE_STEP = 1.5;

/**
 * One gas cloud at system zoom (f < 500): bitmap_2 rendered whole at its own method_146 scale (what the C# shows
 * while the whole cloud is in view), and — magnified further — a patch of the visible region at the C# scale.
 */
export class GasCloudView {
    readonly root = new Container();
    private readonly full = new Sprite(Texture.EMPTY);
    private readonly patch = new Sprite(Texture.EMPTY);
    private base: RgbaImage | null = null;
    private fractal: CFractal | null = null;
    private fullJob: GasCloudDetailJob | null = null;
    private patchJob: GasCloudDetailJob | null = null;
    private patchSrc: PxRect | null = null;
    private patchScale = 0;
    /** Most-recently-used order of clouds holding generated art (shared by all views). */
    private static readonly lru: GasCloudView[] = [];
    /** The one view holding a magnified patch. */
    private static patchOwner: GasCloudView | null = null;

    constructor(
        readonly cloud: Habitat,
        private readonly generate: (cloud: Habitat) => RgbaImage,
    ) {
        this.full.anchor.set(0.5);
        this.root.addChild(this.full, this.patch);
        this.root.position.set(cloud.xpos, cloud.ypos);
        this.root.visible = false;
        this.full.visible = false;
        this.patch.visible = false;
    }

    /** Whether the generated art is in memory (tests / diagnostics). */
    get hasArt(): boolean {
        return this.base !== null;
    }

    /** Whether the cloud is drawn at zoom factor `f` over the world rect `view` (f < 500 and on screen). */
    inView(f: number, view: PxRect): boolean {
        const d = this.cloud.diameter;
        return (
            f < SYSTEM_PASS_MAX_FACTOR &&
            this.cloud.xpos + d > view.x &&
            this.cloud.xpos - d < view.x + view.w &&
            this.cloud.ypos + d > view.y &&
            this.cloud.ypos - d < view.y + view.h
        );
    }

    /** `view` = the camera's world rect; `f` the zoom factor. */
    update(f: number, view: PxRect, budget: GasCloudFrameBudget): void {
        const d = this.cloud.diameter;
        if (!this.inView(f, view)) {
            this.root.visible = false;
            return;
        }
        if (this.base === null) {
            if (budget.generations <= 0) {
                this.root.visible = false;
                return;
            }
            budget.generations--;
            this.base = this.generate(this.cloud);
            // MainView.1.cs 4538: new SectorCloudGenerator(HabitatIndex, 4) — its CFractal(HabitatIndex, 0.35, 2.6).
            this.fractal = new CFractal(this.cloud.habitatIndex, 0.35, 2.6);
            this.touch();
        }
        const base = this.base;
        const fractal = this.fractal!;
        this.root.visible = true;
        const s = d / base.width; // world units per bitmap pixel
        // The whole cloud at the C# scale for a source as wide as the bitmap (min(10, 400 / width)).
        if (this.full.texture === Texture.EMPTY) {
            this.fullJob ??= new GasCloudDetailJob(base, { x: 0, y: 0, w: base.width, h: base.height }, gasCloudDetailScale(base.width), fractal);
            if (budget.ms > 0) {
                const t0 = performance.now();
                const tex = this.fullJob.step(budget.ms);
                budget.ms -= performance.now() - t0;
                if (tex !== null) {
                    this.full.texture = tex;
                    this.fullJob = null;
                }
            }
        }
        const fullReady = this.full.texture !== Texture.EMPTY;
        if (fullReady) this.full.scale.set(d / this.full.texture.width, (base.height * s) / this.full.texture.height);
        // method_136: the region under the view, inflated 2x and clipped, re-rendered at min(10, 400 / width).
        const visible = gasCloudVisibleRect(this.cloud, base.width, base.height, view);
        let patchShown = false;
        if (visible !== null && fullReady) {
            const region = clipRect(inflateRect(visible, 2), base.width, base.height);
            const scale = gasCloudDetailScale(region.w);
            if (scale > gasCloudDetailScale(base.width) * PATCH_SCALE_STEP) {
                // Regenerate when the view leaves the last region (1.2x guard, method_136 4570) or the zoom moved on.
                const guard = clipRect(inflateRect(inflateRect(visible, 1.2), 0.99), base.width, base.height);
                const current = this.patchSrc !== null && rectContains(this.patchSrc, guard) && Math.abs(this.patchScale / scale - 1) < 0.25;
                if (!current && (this.patchJob === null || !rectContains(this.patchJob.src, guard) || Math.abs(this.patchJob.scale / scale - 1) >= 0.25)) {
                    this.patchJob = new GasCloudDetailJob(base, region, scale, fractal);
                }
                if (this.patchJob !== null && budget.ms > 0) {
                    const t0 = performance.now();
                    const tex = this.patchJob.step(budget.ms);
                    budget.ms -= performance.now() - t0;
                    if (tex !== null) {
                        this.setPatch(tex, this.patchJob.src, this.patchJob.scale);
                        this.patchJob = null;
                    }
                }
                patchShown = this.patchSrc !== null && rectContains(this.patchSrc, visible);
            } else {
                this.patchJob = null;
            }
        }
        if (patchShown) {
            const r = this.patchSrc!;
            const left = -d / 2;
            const top = -(base.height * s) / 2;
            this.patch.position.set(left + r.x * s, top + r.y * s);
            this.patch.scale.set((r.w * s) / this.patch.texture.width, (r.h * s) / this.patch.texture.height);
        }
        this.patch.visible = patchShown;
        this.full.visible = fullReady && !patchShown;
        if (patchShown || fullReady) this.touch();
    }

    private setPatch(tex: Texture, src: PxRect, scale: number): void {
        const owner = GasCloudView.patchOwner;
        if (owner !== null && owner !== this) owner.dropPatch();
        this.dropPatch();
        this.patch.texture = tex;
        this.patchSrc = src;
        this.patchScale = scale;
        GasCloudView.patchOwner = this;
    }

    private dropPatch(): void {
        if (this.patch.texture !== Texture.EMPTY) this.patch.texture.destroy(true);
        this.patch.texture = Texture.EMPTY;
        this.patch.visible = false;
        this.patchSrc = null;
        this.patchJob = null;
        if (GasCloudView.patchOwner === this) GasCloudView.patchOwner = null;
    }

    private touch(): void {
        const lru = GasCloudView.lru;
        const i = lru.indexOf(this);
        if (i === lru.length - 1 && i >= 0) return;
        if (i >= 0) lru.splice(i, 1);
        lru.push(this);
        while (lru.length > GAS_CLOUD_CACHE_LIMIT) lru.shift()!.release();
    }

    /** Free the generated art (it is regenerated, identically, the next time the cloud is in view). */
    release(): void {
        this.dropPatch();
        if (this.full.texture !== Texture.EMPTY) this.full.texture.destroy(true);
        this.full.texture = Texture.EMPTY;
        this.full.visible = false;
        this.base = null;
        this.fractal = null;
        this.fullJob = null;
        const i = GasCloudView.lru.indexOf(this);
        if (i >= 0) GasCloudView.lru.splice(i, 1);
    }
}

/**
 * The system-pass location fill (MainView.1.cs method_76 94-139) for super novae: below f 150, with a SuperNova galaxy
 * location within half the view diagonal * f of the view centre, the whole view is filled with supernovaFillColour —
 * opaque, so it hides the backdrop and the nebula art beneath it (the Main View puts it just under the systems).
 * TODO(port): the same fill's NebulaCloud colour (method_122: the galaxy nebula image bitmap_182's pixel x2, which the
 * port does not build) and the lightning flash (method_28's (192,224,192,224) frames; the thunder is
 * audio/mainViewSounds.ts) — MainView.1.cs method_76 94-139.
 */
export class NovaFill {
    readonly sprite = new Sprite(Texture.WHITE);
    constructor() {
        this.sprite.visible = false;
    }

    update(inNova: boolean, f: number, view: PxRect, utcMs: number): void {
        if (!inNova || f >= NOVA_FILL_MAX_FACTOR) {
            this.sprite.visible = false;
            return;
        }
        this.sprite.visible = true;
        this.sprite.tint = supernovaFillColour(f, utcMs);
        this.sprite.position.set(view.x, view.y);
        this.sprite.scale.set(view.w / this.sprite.texture.width, view.h / this.sprite.texture.height);
    }
}

/** MainView.cs 672 double_9 * f: the range (world units) the fill tests the SuperNova locations against. */
export function novaFillRange(viewWidthPx: number, viewHeightPx: number, f: number): number {
    return Math.sqrt(Math.pow(viewWidthPx / 2, 2) + Math.pow(viewHeightPx / 2, 2)) * f;
}
