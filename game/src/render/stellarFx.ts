// Black holes, super novae and gas clouds in the Main View — ports of what DW:U 1.9.5 draws for them at each zoom
// factor f (= 1 / Camera.zoom):
//
// Black hole
//   - f < 500, system pass (MainView.1.cs method_76 649-722): star_blackhole_0 (texture2D_12[0]) drawn three times,
//     centred, at 1.0 / 0.44 / 0.2 x the star's drawn size (max(4, Diameter / f) px), each rotated by double_4 / 5.3,
//     double_4 / 2.3 and double_4 (double_4 += game seconds * 0.4) and tinted by one of four palettes picked by
//     HabitatIndex % 4; then the 100 BlkHole-* accretion frames (texture2D_13 = bitmap_200: each frame's 10 % border
//     cropped, scaled to 100 x 100, Main.Part13.cs LoadStars 1144-1162) at 0.08 x, 15 fps (method_117), untinted.
//   - f > 150, galaxy pass (MainView.2.cs method_250 5337-5374, 5476-5490): the map-star picture
//     bitmap_196[MapPictureRef] in a square of 2 * val3 px, val3 = max(MaxSolarSystemSize, TSV radius) / f * 2, at
//     least 5 and, below f 5100, clamped to 11..17. It is on spriteBatch_1, drawn over everything of spriteBatch_0.
//   Nothing spawns there and nothing else is drawn: the "Pull" (ShipPull) and "Event Horizon" (ShipDamage) galaxy
//   locations SetupSun adds (Galaxy.5.cs 1329-1352) are sim effects with no Main View art.
//
// Super nova
//   - f > 150, galaxy pass (MainView.2.cs 5359-5362, 5430-5434, 5449-5458, 5491-5501): the nova picture
//     bitmap_206[NovaImageIndexMajor] in a square of max(8, (int)(val4 * 1.3)) px, val4 = (int)(NovaProgression * 2 / f)
//     — world-linear, 2.6 x NovaProgression across (1.3 x the SuperNova location's diameter).
//   - f < 150, system pass: the star itself is not drawn (MainView.1.cs 730 `Type != SuperNova`); instead, while the
//     view centre is within half the view diagonal of a SuperNova galaxy location (DetermineGalaxyLocationsInRangeAtPoint,
//     MainView.1.cs 94-139), the whole view is filled with the pulsing method_29 colour (MainView.cs 1835-1852),
//     darkened by zoom, opaque, over the backdrop and under every system / ship. The location's ShieldReduction effect
//     on ships has no art.
//
// Gas cloud (a SystemInfo whose SystemStar is a GasCloud habitat; GenerateGasCloud places it inside a NebulaCloud
// location, Galaxy.4.cs 2834-2844)
//   - f > 150, galaxy pass (MainView.2.cs 5390-5394): the "+" cross — galaxyMarkers.ts.
//   - f < 500, system pass (MainView.1.cs 724-727 DrawGasCloudToMainXna, MainView.2.cs 2072-2099): bitmap_2, one
//     cloud generated by nebulaCloudGenerator_1.GenerateNebulaBackdrop(HabitatIndex, 255, colour scheme 20 + method_135
//     by type, min(100, Diameter), transparent, isGasCloud) (MainView.1.cs method_135 4507-4540), stretched over
//     Diameter x Diameter * h / w world units centred on the cloud (method_141), untinted. Magnified, the visible part
//     is re-rendered by method_146 (MainView.2.cs 20-103): the region of the bitmap under the view, inflated 2x, scaled
//     up min(10, 400 / width) times (at most 2000 px), with its alpha multiplied by (fBm + 1) / 2 of a CFractal
//     (seed HabitatIndex, H 0.35, lacunarity 2.6, 6 octaves) sampled at 10 / bitmap width per bitmap pixel
//     (SectorCloudGenerator.FbmImageTransparent); it is regenerated when the view leaves 1.2x of the last region.
//   No radiation field is drawn (MainView has no use of the Solar / Microwave / Xray radiation values).
//
// Render-only: nothing here touches sim state or the sim's random streams.

