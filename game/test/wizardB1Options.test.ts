// [wizardB1] New-game wizard options wired to the engine (Start.1.cs 3685-3850 btnStartNewGameStart_Click, Start.cs 5613
// btnJumpStartTheGalaxyNext_Click → Start.2.cs CreateGameFromSettings → Galaxy.4.cs 2088 ctor): each wizard option maps to
// the original's value, and that value changes the game the way the C# reads it.
import { beforeAll, describe, expect, it } from 'vitest';
import { createGame, ensureAggressiveAiRaces, type ResolvedStart } from '../src/sim/game';
import { Random } from '../src/sim/random';
