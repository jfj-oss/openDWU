let gameData: GameData;
beforeAll(async () => {
    gameData = await loadGameDataFs();
}, 60000);

const NAMES = Array.from({ length: 1500 }, (_, i) => `N${i}`);
const start = (o: Partial<StartGameOptions> = {}): StartGameOptions => ({ ...defaultStartGameOptions(), seed: 7, raceName: 'Human', ...o });

describe('wizard slider → Galaxy ctor value (Start.1.cs 3687-3694, 3739)', () => {
    it('maps Alien Life, Space Creatures, Aggression and Difficulty through method_67 / 62 / 71 / 201', () => {
        const life = [150, 250, 400, 700, 1000];
        const creatures = [0.0, 0.3, 0.6, 1.0];
        const aggression = [0.9, 1.1, 1.3, 1.5, 1.7];
        const difficulty = [0.7, 1.0, 1.25, 1.6, 2.0];
        life.forEach((v, i) => expect(toCreateGameOptions(start({ alienLifeIndex: i }), gameData, NAMES).lifePrevalence).toBe(v));
        creatures.forEach((v, i) => expect(toCreateGameOptions(start({ spaceCreaturesIndex: i }), gameData, NAMES).creaturePrevalence).toBe(v));
        aggression.forEach((v, i) => expect(toCreateGameOptions(start({ aggressionIndex: i }), gameData, NAMES).aggressionLevel).toBe(v));
        difficulty.forEach((v, i) => expect(toCreateGameOptions(start({ difficultyIndex: i }), gameData, NAMES).difficultyLevel).toBe(v));
        expect([0, 1, 2, 3, 4].map(alienLifeFor)).toEqual(life);
        expect([0, 1, 2, 3].map(spaceCreaturesFor)).toEqual(creatures);
        expect([0, 1, 2, 3, 4].map(aggressionFor)).toEqual(aggression);
        expect([0, 1, 2, 3, 4].map(difficultyFor)).toEqual(difficulty);
    });

    it('defaults to the original fresh-install positions (Main.Part9.cs method_259): 400 life, 0.6 creatures, aggression 1.1, difficulty 1.0', () => {
        const c = toCreateGameOptions(start(), gameData, NAMES);
        expect(c.lifePrevalence).toBe(400);
        expect(c.creaturePrevalence).toBe(0.6);
        expect(c.aggressionLevel).toBe(1.1);
        expect(c.difficultyLevel).toBe(1.0);
        expect(c.spawnNewEmpires).toBe(true);
        expect(c.allowTechTrading).toBe(true);
        expect(c.allowGiantKaltorGeneration).toBe(true);
        expect(c.destroyedPiratesDoNotRespawn).toBe(false);
        expect(c.autogeneratedAiEmpires).toBe(true);
        // Story box: Distant Worlds + Return of the Shakturi on; Shadows only offered in a PreWarp galaxy.
        expect(c.storyDistantWorldsEnabled).toBe(true);
        expect(c.victoryConditions!.enableStoryEvents).toBe(true);
        expect(c.victoryConditions!.enableStoryEventsShadows).toBe(false);
        expect(toCreateGameOptions(start({ galaxyExpansionIndex: 0 }), gameData, NAMES).victoryConditions!.enableStoryEventsShadows).toBe(true);
        // Corruption: the player's slider (method_63, default Normal = 1.1) and every AI start's EmpireStart default 1.1.
        expect(c.player.corruptionMultiplier).toBe(1.1);
        expect(c.aiEmpires.every((e) => e.corruptionMultiplier === 1.1)).toBe(true);
        expect([0, 1, 2, 3].map(corruptionMultiplierFor)).toEqual([0.9, 1.1, 1.3, 1.5]);
        expect(c.player.homeSystemFavourability).toBe('Normal');
        expect(c.player.startLocation).toBe('(Random)');
        expect(c.player.playAsPirate).toBeUndefined();
    });

    it('passes the option checkboxes, story toggles, home system and start location through', () => {
        const o = start({ spawnNewEmpires: false, allowTechTrading: false, allowGiantKaltorGeneration: false, destroyedPiratesDoNotRespawn: true, homeSystemIndex: 4, startLocationIndex: 3, shape: GalaxyShape.Spiral, empireCorruptionIndex: 3 });
        o.victory = { ...o.victory, enableStoryDistantWorlds: false, enableStoryEvents: false };
        const c = toCreateGameOptions(o, gameData, NAMES);
        expect([c.spawnNewEmpires, c.allowTechTrading, c.allowGiantKaltorGeneration, c.destroyedPiratesDoNotRespawn]).toEqual([false, false, false, true]);
        expect(c.storyDistantWorldsEnabled).toBe(false);
        expect(c.victoryConditions!.enableStoryEvents).toBe(false);
        expect(c.player.homeSystemFavourability).toBe('Excellent');
        expect(c.player.startLocation).toBe('Far Regions');
        expect(c.player.corruptionMultiplier).toBe(1.5);
        // A manual empire list skips method_104.
        o.otherEmpires = { ...o.otherEmpires, manual: [{ race: 'Human', governmentId: -1, name: '' }] };
        expect(toCreateGameOptions(o, gameData, NAMES).autogeneratedAiEmpires).toBe(false);
    });
});

describe('Galaxy ctor values change generation (Galaxy.4.cs 2137-2153)', () => {
    const gen = (o: { creaturePrevalence?: number; lifePrevalence?: number; allowGiantKaltorGeneration?: boolean }) =>
        generateGalaxy({ seed: 3, shape: GalaxyShape.Spiral, starCount: 300, sectorWidth: 8, sectorHeight: 8, systemNames: NAMES, gameData, ...o });

    it('scales the space-creature count with _CreaturePrevalence (Galaxy.6.cs SelectCreatures)', () => {
        const none = gen({ creaturePrevalence: 0.0 });
        const few = gen({ creaturePrevalence: 0.3 });
        const many = gen({ creaturePrevalence: 1.0 });
        expect(none.creaturePrevalence).toBe(0.0);
        expect(none.creatures.length).toBe(0);
        expect(few.creatures.length).toBeGreaterThan(0);
        expect(many.creatures.length).toBeGreaterThan(few.creatures.length * 2);
    }, 120000);

    it('AllowGiantKaltorGeneration = false places no Kaltors', () => {
        const on = gen({ creaturePrevalence: 1.0 });
        const off = gen({ creaturePrevalence: 1.0, allowGiantKaltorGeneration: false });
        expect(on.creatures.some((c) => c.type === CreatureType.Kaltor)).toBe(true);
        expect(off.allowGiantKaltorGeneration).toBe(false);
        expect(off.creatures.some((c) => c.type === CreatureType.Kaltor)).toBe(false);
    }, 120000);

    it('limits independent alien colonies with _LifePrevalence (Galaxy.6.cs CheckIndependentColonyLimitForRace)', () => {
        // SetupAlienRacePopulations needs empire starts for its race regions (SelectPopulation reads the nearest one).
        const empireStarts = gameData.races.filter((r) => r.playable).slice(0, 4).map((resolvedRace) => ({ resolvedRace, projectedColonyAmount: 1 }));
        const rare = generateGalaxy({ seed: 3, shape: GalaxyShape.Spiral, starCount: 300, sectorWidth: 8, sectorHeight: 8, systemNames: NAMES, gameData, empireStarts, lifePrevalence: 150 });
        const common = generateGalaxy({ seed: 3, shape: GalaxyShape.Spiral, starCount: 300, sectorWidth: 8, sectorHeight: 8, systemNames: NAMES, gameData, empireStarts, lifePrevalence: 1000 });
        expect(common.independentCount).toBeGreaterThan(0);
        expect(rare.lifePrevalence).toBe(150);
        expect(rare.independentCount).toBeLessThan(common.independentCount);
        expect(() => gen({ lifePrevalence: 0 })).toThrow(RangeError);
    }, 120000);

    it('unset options keep the C# ctor defaults (the harness game is unchanged)', () => {
        const g = gen({});
        expect([g.lifePrevalence, g.creaturePrevalence, g.allowGiantKaltorGeneration, g.difficultyLevel, g.aggressionLevel, g.spawnNewEmpires]).toEqual([1000, 1.0, true, 1.0, 1.0, true]);
    }, 120000);
});

describe('createGame with wizard options', () => {
    it('difficulty sets Galaxy.DifficultyLevel and the empire difficulty factors (Galaxy.cs 1417 SetEmpireDifficultyFactors)', () => {
        const game = createGame({ ...tickGameOptions(gameData), difficultyLevel: 2.0, allowTechTrading: false, spawnNewEmpires: false, destroyedPiratesDoNotRespawn: true });
        const g = game.galaxy;
        expect(g.difficultyLevel).toBe(2.0);
        expect(g.allowTechTrading).toBe(false);
        expect(g.spawnNewEmpires).toBe(false);
        expect(g.destroyedPiratesDoNotRespawn).toBe(true);
        const p = game.playerEmpire;
        expect(p.difficultyLevel).toBeCloseTo(2.0 + p.difficultyLevelModifier, 12);
        expect(p.difficultyFactors!.researchRate).toBeCloseTo(1 / p.difficultyLevel, 12);
        const ai = g.empires.find((e) => e !== p)!;
        expect(ai.difficultyLevel).toBeCloseTo(1.0 + (1.0 - Math.sqrt(2.0)) + ai.difficultyLevelModifier, 12);
    }, 120000);

    it('the Custom Pirate playstyle creates a pirate player empire with the chosen playstyle (Start.2.cs 567-729)', () => {
        const o = start({ empireType: 'CustomPirate', piratePlayStyleIndex: 2, starCountIndex: 1, dimensionIndex: 1, otherEmpires: { autogenerate: true, empireCount: 3, manual: [] } });
        const c = toCreateGameOptions(o, gameData, NAMES);
        expect(c.player.playAsPirate).toBe(true);
        expect(c.player.piratePlayStyle).toBe(PiratePlayStyle.Mercenary);
        // Start.cs 3776 method_45: no Return of the Shakturi for a pirate.
        expect(c.victoryConditions!.enableStoryEvents).toBe(false);
        const game = createGame(c);
        const p = game.playerEmpire;
        expect(game.galaxy.playerEmpire).toBe(p);
        expect(p.pirateEmpireBaseHabitat).not.toBeNull();
        expect(game.galaxy.pirateEmpires).toContain(p);
        expect(game.galaxy.empires).not.toContain(p);
        expect(p.piratePlayStyle).toBe(PiratePlayStyle.Mercenary);
        expect(game.galaxy.storyReturnOfTheShakturiEnabled).toBe(false);
    }, 120000);

    it('the Custom Pirate playstyle raises a PreWarp tech level to Normal (Start.cs nVkoJxpyvO)', () => {
        const o = start({ empireTechLevelIndex: 0 });
        applyEmpireTypeChoice(o, 'CustomPirate');
        expect(o.empireTechLevelIndex).toBe(1);
    });
});

