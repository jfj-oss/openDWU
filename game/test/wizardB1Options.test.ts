describe('DestroyedPiratesDoNotRespawn (Galaxy.9.cs 23-30)', () => {
    function respawned(flag: boolean, nowMs: number): number {
        const game = cachedTickGame(gameData);
        const g = game.galaxy;
        expect(g.pirateEmpires.length).toBeGreaterThan(0);
        g.destroyedPiratesDoNotRespawn = flag;
        g.nowMs = nowMs;
        g.pirateEmpires.length = 0; // every faction destroyed
        generateNewPirateEmpires(g, { independentColonies: g.independentColonies, startingAge: g.startingAge, difficultyLevel: g.difficultyLevel }, { piratePrevalence: g.piratePrevalence, maximumEmpireAmount: g.maximumEmpireAmount, pirateProximity: g.pirateProximity });
        return g.pirateEmpires.length;
    }

    it('replaces destroyed factions by default', () => {
        expect(respawned(false, 600000)).toBeGreaterThan(0);
    }, 120000);

    it('keeps the current count once more than 300000 ms have passed', () => {
        expect(respawned(true, 600000)).toBe(0);
    }, 120000);

    it('still generates factions during the first 300000 ms', () => {
        expect(respawned(true, 300000)).toBeGreaterThan(0);
    }, 120000);
});

describe('Start.2.cs method_104: aggressive races among the four largest auto-generated starts', () => {
    it('swaps later aggressive starts into the top four (2 at aggression >= 1.1), both ending with the aggressive start\'s age', () => {
        const playable = gameData.races.filter((r) => r.playable);
        const aggressive = playable.filter((r) => r.aggression >= 115 && r.intelligence >= 90);
        const calm = playable.filter((r) => !aggressive.includes(r));
        expect(aggressive.length).toBeGreaterThanOrEqual(2);
        const mk = (race: (typeof playable)[number], age: number): ResolvedStart => ({ opts: { race: race.name, homeSystemFavourability: 'Normal', age, techLevel: 0.5 }, resolvedRace: race, projectedColonyAmount: 0 });
        const run = (level: number): ResolvedStart[] => {
            const list = [mk(calm[0], 3), mk(calm[1], 3), mk(calm[2], 3), mk(calm[3], 3), mk(aggressive[0], 1), mk(aggressive[1], 1), mk(calm[4], 1), mk(calm[5], 1)];
            ensureAggressiveAiRaces(list, playable, level, '', new Random(1));
            return list;
        };
        const ages = (l: ResolvedStart[]) => l.map((e) => e.opts.age).sort();
        const aggressiveAges = (l: ResolvedStart[]) => l.filter((e) => aggressive.includes(e.resolvedRace!)).map((e) => e.opts.age);
        // Aggression 1.1: num = 2 → two swaps; each displaced age-3 start takes the aggressive start's age 1 (C# quirk).
        const two = run(1.1);
        expect(ages(two)).toEqual([1, 1, 1, 1, 1, 1, 3, 3]);
        expect(aggressiveAges(two)).toEqual([1, 1]);
        // Below 1.1: num = 1 → one swap.
        expect(ages(run(0.9))).toEqual([1, 1, 1, 1, 1, 3, 3, 3]);
    });
});
