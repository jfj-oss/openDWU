const json = (body) => new Response(body, { status: 200, headers: { 'Content-Type': 'application/json' } });

// Local model servers (Ollama, LM Studio, llama-server) on this machine: Ollama answers 403 to an Origin it does not
// know, and the game's pages come from dwu://app, so every LLM request failed unless the user set OLLAMA_ORIGINS.
// For requests to localhost only, drop the dwu:// Origin, accept the answer for the page (CORS headers) and answer
// the CORS preflight ourselves. No other host is touched.
const LOCAL_MODEL_URLS = ['http://127.0.0.1/*', 'http://localhost/*', 'http://[::1]/*'];
function allowLocalModelServers(ses) {
    const fromApp = new Set();
    ses.webRequest.onBeforeSendHeaders({ urls: LOCAL_MODEL_URLS }, (details, callback) => {
        const h = details.requestHeaders;
        const origin = h.Origin ?? h.origin ?? '';
        if (/^dwu:/i.test(origin)) {
            delete h.Origin;
            delete h.origin;
            fromApp.add(details.id);
        }
        callback({ requestHeaders: h });
    });
    ses.webRequest.onHeadersReceived({ urls: LOCAL_MODEL_URLS }, (details, callback) => {
        if (!fromApp.delete(details.id)) return callback({});
        const headers = {};
        for (const [k, v] of Object.entries(details.responseHeaders ?? {})) if (!/^access-control-/i.test(k)) headers[k] = v;
        headers['Access-Control-Allow-Origin'] = ['dwu://app'];
        headers['Access-Control-Allow-Headers'] = ['*'];
        headers['Access-Control-Allow-Methods'] = ['GET, POST, OPTIONS'];
        // The preflight reaches the server without an Origin (a 404 there): it is ours to allow.
        if (details.method === 'OPTIONS') return callback({ responseHeaders: headers, statusLine: 'HTTP/1.1 204 No Content' });
        callback({ responseHeaders: headers });
    });
}

// Must be registered after app ready: protocol.handle touches the default
// session, which is only available once the app is ready.
app.whenReady().then(() => {
    allowLocalModelServers(session.defaultSession);
    protocol.handle('dwu', async (request) => {
        try {
            const url = new URL(request.url);
            // dwu://app/<rest> — host is "app", pathname starts with "/"
            let rest = decodeURIComponent(url.pathname.replace(/^\/+/, ''));
            // The query string (?autostart=1 etc.) is for the page, not the file.

            if (rest.startsWith('assets/dwu/')) {
                // Original DW:U data/art from the user's install folder.
                if (!installDir) {
                    return new Response('DW:U install folder not configured', { status: 503 });
                }
                const fileRel = rest.slice('assets/dwu/'.length);
                const resolved = resolver.resolveInsideRoot(installDir, fileRel);
                if (!resolved) {
                    return new Response(`Not found: ${fileRel}`, { status: 404 });
                }
                if (!fs.statSync(resolved).isFile()) {
                    return new Response(`Not a file: ${fileRel}`, { status: 404 });
                }
                if (isProfiledImagePath(resolved)) {
                    // Original art with its embedded colour profile removed: the original's GDI+ load ignores it,
                    // so the renderer must decode raw values too (desktop/colorProfile.cjs; same as the Vite dev
                    // server's /assets/dwu/ middleware in vite.config.ts).
                    const body = stripColorProfile(await fs.promises.readFile(resolved));
                    const type = /\.png$/i.test(resolved) ? 'image/png' : 'image/jpeg';
                    return new Response(body, { status: 200, headers: { 'Content-Type': type, 'Content-Length': String(body.length) } });
                }
                return net.fetch(pathToFileURL(resolved).href, request);
            }

            if (rest === 'user-music/index.json') {
                // The player's playlists (Options → Music & Mood; src/audio/userMusic.ts), read fresh each time.
                userMusic.ensureMusicFolder(MUSIC_DIR());
                musicResolver.clearCache();
                return new Response(JSON.stringify(userMusic.listPlaylists(MUSIC_DIR())), { status: 200, headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' } });
            }
            if (rest.startsWith('user-music/')) {
                const fileRel = rest.slice('user-music/'.length);
                const resolved = musicResolver.resolveInsideRoot(MUSIC_DIR(), fileRel);
                if (!resolved || !fs.existsSync(resolved) || !fs.statSync(resolved).isFile()) return new Response(`Not found: ${fileRel}`, { status: 404 });
                return net.fetch(pathToFileURL(resolved).href, request);
            }

            if (rest === 'asset-manifest.json') {
                // Folder listings of the USER's install (desktop/assetManifest.cjs), built in setInstallDir; {} without
                // one, like the dev server's manifest when no install is linked.
                return json(assetManifestBody);
            }

            if (rest.startsWith('theme-manifest/')) {
                // Themes of the USER's install (Customization subfolders + each one's file index). desktop/themeIndex.cjs.
                const body = themeBody(rest.slice('theme-manifest/'.length));
                if (body === null) return new Response(`Not found: ${rest}`, { status: 404 });
                return json(body);
            }

            // Everything else: the built game from dist/.
            const resolved = distResolver.resolveInsideRoot(DIST_DIR, rest || 'index.html');
            if (!resolved || !fs.existsSync(resolved) || !fs.statSync(resolved).isFile()) {
                return new Response(`Not found: ${rest}`, { status: 404 });
            }
            // The page itself carries the machine's total RAM (src/systemMemory.ts: the sim-worker default needs
            // 16 GB+; navigator.deviceMemory is capped at 8).
            if ((rest || 'index.html') === 'index.html') {
                const gib = (os.totalmem() / 2 ** 30).toFixed(1);
                const html = (await fs.promises.readFile(resolved, 'utf8')).replace('</head>', `<meta name="dwu-system-memory-gib" content="${gib}">\n</head>`);
                return new Response(html, { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
            }
            return net.fetch(pathToFileURL(resolved).href, request);
        } catch (err) {
            console.error('dwu:// handler error:', err);
            return new Response(String(err && err.message ? err.message : err), { status: 500 });
        }
    });
});

