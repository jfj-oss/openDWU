// Electron main process for the DW:U recreation (openDWU).
//
// Serves the built game (dist/) over a privileged custom scheme, dwu://app/…,
// and maps dwu://app/assets/dwu/<path> to <DW:U install dir>/<path> so the
// renderer can fetch original data/art by URL exactly like it does under
// `npm run dev` (where Vite serves the public/assets/dwu symlink). PNG/JPEG
// art is served without its embedded colour profile (colorProfile.cjs), as
// the original decodes it.
//
// Nothing from the original game ships with the app: the install-derived
// listings the browser cannot make (asset-manifest.json, theme-manifest/) are
// built here from the player's install folder at launch and whenever the
// folder changes (assetManifest.cjs, themeIndex.cjs), and served from memory.
//
// Also here: finding the install (installDir.cjs) or asking for it in the
// setup window (setup.html), the menu (game folder, update check), and the
// daily update check against GitHub Releases (updateCheck.cjs).
//
// The renderer stays platform-neutral: no Node APIs in src/, everything goes
// through URLs under /assets/dwu/.

const { app, BrowserWindow, Menu, dialog, protocol, net, nativeImage, ipcMain, shell } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const { pathToFileURL } = require('node:url');
const { stripColorProfile, isProfiledImagePath } = require('./colorProfile.cjs');
const themeIndex = require('./themeIndex.cjs');
const { buildAssetManifest } = require('./assetManifest.cjs');
const { createResolver } = require('./resolvePath.cjs');
const installLib = require('./installDir.cjs');
const updates = require('./updateCheck.cjs');

// dist/ lives next to desktop/ in the repo; when packaged it is copied into
// resources/ by @electron/packager (extraResource in scripts/package-desktop.mjs).
const DIST_DIR = app.isPackaged ? path.join(process.resourcesPath, 'dwu-dist') : path.join(__dirname, '..', 'dist');
// Our own app icon (generated by scripts/make-icon.mjs at packaging time); absent when running unpackaged.
const OWN_ICON = app.isPackaged ? path.join(process.resourcesPath, 'icon.png') : null;

// The packaged app's package.json is the stage one written by package-desktop.mjs (version from game/package.json);
// unpackaged it is game/package.json.
const PKG = (() => {
    try {
        return require('../package.json');
    } catch {
        return {};
    }
})();
const APP_VERSION = app.isPackaged ? app.getVersion() : String(PKG.version ?? app.getVersion());
const UPDATE_REPO = updates.repoSlug(PKG.repository) ?? 'jfj-oss/openDWU';
const APP_ID = 'local.dwureup.dwu';
const PRODUCT = 'openDWU';
// Where the shell menu is, for the setup window's hint (macOS: the app menu, titled with the product name).
const MENU_SHORTCUT_LABEL = process.platform === 'darwin' ? `the ${app.name} menu` : 'Ctrl+Shift+O';

const CONFIG_FILE = () => path.join(app.getPath('userData'), 'config.json');

// ---------------------------------------------------------------------------
// config.json: { installDir, lastUpdateCheck, skippedVersion, checkForUpdates }
// ---------------------------------------------------------------------------

function readConfig() {
    try {
        const cfg = JSON.parse(fs.readFileSync(CONFIG_FILE(), 'utf8'));
        return cfg && typeof cfg === 'object' && !Array.isArray(cfg) ? cfg : {};
    } catch {
        return {}; // missing or invalid config.json
    }
}

function updateConfig(patch) {
    const cfg = { ...readConfig(), ...patch };
    try {
        fs.mkdirSync(path.dirname(CONFIG_FILE()), { recursive: true });
        const tmp = `${CONFIG_FILE()}.tmp`;
        fs.writeFileSync(tmp, JSON.stringify(cfg, null, 2) + '\n');
        fs.renameSync(tmp, CONFIG_FILE());
    } catch (err) {
        console.warn(`Could not write ${CONFIG_FILE()}: ${err.message}`);
    }
    return cfg;
}

// ---------------------------------------------------------------------------
// Install-dir discovery
// ---------------------------------------------------------------------------

/** Windows registry string value via reg.exe (no native modules), or null. */
function readRegistry(key, value) {
    if (process.platform !== 'win32') return null;
    try {
        const out = execFileSync('reg', ['query', key, '/v', value], { encoding: 'utf8', timeout: 3000, windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'] });
        return installLib.parseRegQueryValue(out, value);
    } catch {
        return null; // key or value absent
    }
}

function candidateOpts() {
    return { platform: process.platform, home: os.homedir(), env: process.env, registry: readRegistry };
}

/**
 * Find the DW:U install dir without asking: $DWU_DIR (not saved; for scripts/tests, same variable as
 * `npm run import-assets`) → saved config → the platform's usual places (saved when found).
 * Returns { dir, previous }: previous is a saved folder that is no longer valid (for the setup window's message).
 */
function discoverInstallDir() {
    const envDir = process.env.DWU_DIR;
    if (envDir) {
        if (installLib.checkInstallDirExact(envDir).ok) return { dir: envDir, previous: null };
        console.warn(`DWU_DIR=${envDir} is not a DW:U install folder (needs images/ and races.txt); ignoring it.`);
    }
    const saved = readConfig().installDir;
    if (typeof saved === 'string' && installLib.checkInstallDirExact(saved).ok) return { dir: saved, previous: null };
    const found = installLib.findInstallDir(candidateOpts());
    if (found) {
        updateConfig({ installDir: found });
        return { dir: found, previous: null };
    }
    return { dir: null, previous: typeof saved === 'string' ? saved : null };
}

// ---------------------------------------------------------------------------
// The current install and everything derived from it
// ---------------------------------------------------------------------------

let installDir = null;
let appIcon = nativeImage.createEmpty();
const resolver = createResolver();
const distResolver = createResolver();
/** Built at launch / on folder change: the JSON bodies of asset-manifest.json and theme-manifest/*. */
let assetManifestBody = '{}';
const themeBodies = new Map(); // name ('index.json' | '<set>.json') -> body | null (404)

function setInstallDir(dir) {
    installDir = dir;
    resolver.clearCache();
    themeBodies.clear();
    const t0 = Date.now();
    assetManifestBody = dir ? JSON.stringify(buildAssetManifest(dir)) : '{}';
    if (dir) {
        const themes = themeIndex.listThemes(dir);
        themeBodies.set('index.json', JSON.stringify(themes));
        for (const t of themes) {
            const idx = themeIndex.buildThemeIndex(dir, t);
            themeBodies.set(`${t}.json`, idx === null ? null : JSON.stringify(idx));
        }
        console.log(`[install] ${dir}: asset manifest ${Math.round(assetManifestBody.length / 1024)} KB, ${themes.length} theme(s) in ${Date.now() - t0} ms`);
    }
    appIcon = makeAppIcon(dir);
    for (const win of BrowserWindow.getAllWindows()) if (!appIcon.isEmpty()) win.setIcon?.(appIcon);
    if (process.platform === 'darwin' && !appIcon.isEmpty()) app.dock?.setIcon(appIcon);
}

/** theme-manifest/<name>: from the table built in setInstallDir; a theme added since is indexed on first request. */
function themeBody(name) {
    if (!installDir) return name === 'index.json' ? '[]' : null;
    if (themeBodies.has(name)) return themeBodies.get(name);
    let body = null;
    if (name.endsWith('.json')) {
        const idx = themeIndex.buildThemeIndex(installDir, name.slice(0, -'.json'.length));
        if (idx !== null) body = JSON.stringify(idx);
    }
    themeBodies.set(name, body);
    return body;
}

// ---------------------------------------------------------------------------
// dwu:// scheme handler
// ---------------------------------------------------------------------------

const json = (body) => new Response(body, { status: 200, headers: { 'Content-Type': 'application/json' } });

// Must be registered after app ready: protocol.handle touches the default
// session, which is only available once the app is ready.
app.whenReady().then(() => {
    protocol.handle('dwu', async (request) => {
        try {
            const url = new URL(request.url);
            // dwu://app/<rest> — host is "app", pathname starts with "/"
            let rest = decodeURIComponent(url.pathname.replace(/^\/+/, ''));
            // The query string (?autostart=1 etc.) is for the page, not the file.

            if (rest.startsWith('assets/dwu/')) {
                // Original DW:U data/art from the user's install folder.
                if (!installDir) {
                    return new Response('DW:U install folder not configured', { status: 503 });
                }
                const fileRel = rest.slice('assets/dwu/'.length);
                const resolved = resolver.resolveInsideRoot(installDir, fileRel);
                if (!resolved) {
                    return new Response(`Not found: ${fileRel}`, { status: 404 });
                }
                if (!fs.statSync(resolved).isFile()) {
                    return new Response(`Not a file: ${fileRel}`, { status: 404 });
                }
                if (isProfiledImagePath(resolved)) {
                    // Original art with its embedded colour profile removed: the original's GDI+ load ignores it,
                    // so the renderer must decode raw values too (desktop/colorProfile.cjs; same as the Vite dev
                    // server's /assets/dwu/ middleware in vite.config.ts).
                    const body = stripColorProfile(await fs.promises.readFile(resolved));
                    const type = /\.png$/i.test(resolved) ? 'image/png' : 'image/jpeg';
                    return new Response(body, { status: 200, headers: { 'Content-Type': type, 'Content-Length': String(body.length) } });
                }
                return net.fetch(pathToFileURL(resolved).href, request);
            }

            if (rest === 'asset-manifest.json') {
                // Folder listings of the USER's install (desktop/assetManifest.cjs), built in setInstallDir; {} without
                // one, like the dev server's manifest when no install is linked.
                return json(assetManifestBody);
            }

            if (rest.startsWith('theme-manifest/')) {
                // Themes of the USER's install (Customization subfolders + each one's file index). desktop/themeIndex.cjs.
                const body = themeBody(rest.slice('theme-manifest/'.length));
                if (body === null) return new Response(`Not found: ${rest}`, { status: 404 });
                return json(body);
            }

            // Everything else: the built game from dist/.
            const resolved = distResolver.resolveInsideRoot(DIST_DIR, rest || 'index.html');
            if (!resolved || !fs.existsSync(resolved) || !fs.statSync(resolved).isFile()) {
                return new Response(`Not found: ${rest}`, { status: 404 });
            }
            // The page itself carries the machine's total RAM (src/systemMemory.ts: the sim-worker default needs
            // 16 GB+; navigator.deviceMemory is capped at 8).
            if ((rest || 'index.html') === 'index.html') {
                const gib = (os.totalmem() / 2 ** 30).toFixed(1);
                const html = (await fs.promises.readFile(resolved, 'utf8')).replace('</head>', `<meta name="dwu-system-memory-gib" content="${gib}">\n</head>`);
                return new Response(html, { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
            }
            return net.fetch(pathToFileURL(resolved).href, request);
        } catch (err) {
            console.error('dwu:// handler error:', err);
            return new Response(String(err && err.message ? err.message : err), { status: 500 });
        }
    });
});

// ---------------------------------------------------------------------------
// Window icon (loaded at runtime from the user's DW:U install folder — art
// can't be committed to the repo — else our own generated icon)
// ---------------------------------------------------------------------------

/**
 * Build the window/dock icon from the install dir. Tries the in-game chrome icon first, then the desktop icon shipped
 * with the game, then the app's own icon. Returns an empty nativeImage if none exists (callers must check isEmpty()).
 */
function makeAppIcon(dir) {
    if (dir) {
        for (const rel of ['images/ui/chrome/galaxy_Icon.png', 'DesktopIcon.ico']) {
            const resolved = resolver.resolveInsideRoot(dir, rel);
            if (!resolved || !fs.existsSync(resolved)) continue;
            const img = nativeImage.createFromPath(resolved);
            if (!img.isEmpty()) return img;
        }
    }
    if (OWN_ICON && fs.existsSync(OWN_ICON)) {
        const img = nativeImage.createFromPath(OWN_ICON);
        if (!img.isEmpty()) return img;
    }
    return nativeImage.createEmpty();
}

