let setupWin = null;
let setupState = null; // { mode, previous, promise, done, finish(result) }

/** Show the setup window. mode 'first-run' resolves 'ok' | 'skip' | 'quit'; mode 'change' resolves 'ok' | 'cancel'. */
function openSetupWindow(mode, previous = null) {
    if (setupWin && !setupWin.isDestroyed()) {
        setupWin.focus();
        return setupState.promise;
    }
    const parent = mode === 'change' ? mainWin ?? undefined : undefined;
    setupWin = new BrowserWindow({
        width: 760,
        height: process.platform === 'darwin' ? 720 : 680,
        minWidth: 560,
        minHeight: 520,
        title: `${PRODUCT} — Distant Worlds: Universe folder`,
        backgroundColor: '#0b1220',
        show: false,
        parent,
        modal: mode === 'change' && process.platform !== 'linux', // Linux WMs handle modal children poorly
        icon: appIcon.isEmpty() ? undefined : appIcon,
        autoHideMenuBar: true,
        webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true, preload: path.join(__dirname, 'setupPreload.cjs') },
    });
    setupWin.setMenuBarVisibility(false);
    const win = setupWin;
    let resolveFn;
    const promise = new Promise((r) => (resolveFn = r));
    const state = { mode, previous, promise, done: false };
    state.finish = (result) => {
        if (state.done) return;
        state.done = true;
        resolveFn(result);
        if (!win.isDestroyed()) win.close();
    };
    setupState = state;
    // Closing the window = Quit (first run) / Cancel (change).
    win.on('closed', () => {
        state.finish(mode === 'first-run' ? 'quit' : 'cancel');
        if (setupWin === win) setupWin = null;
    });
    // Links in the page open in the browser, never in the app.
    win.webContents.setWindowOpenHandler(({ url }) => {
        if (updates.isSafeGithubUrl(url) || /^https:\/\/(store\.steampowered\.com|getwhisky\.app|www\.codeweavers\.com)\//.test(url)) shell.openExternal(url);
        return { action: 'deny' };
    });
    win.webContents.on('will-navigate', (e) => e.preventDefault());
    win.once('ready-to-show', () => win.show());
    win.loadFile(path.join(__dirname, 'setup.html'));
    return promise;
}

function fromSetupWindow(event) {
    return setupWin && !setupWin.isDestroyed() && event.sender === setupWin.webContents;
}

function setupInfo() {
    return {
        mode: setupState?.mode ?? 'first-run',
        platform: process.platform,
        current: installDir,
        previous: setupState?.previous ?? null,
        searched: installLib.installCandidates(candidateOpts()).length,
        version: APP_VERSION,
        menuHint: MENU_SHORTCUT_LABEL,
        home: os.homedir(),
    };
}

// The main menu's Check for Updates (gamePreload.cjs): the manual check, from the game window only.
ipcMain.handle('dwu:check-updates', async (event) => {
    if (mainWin === null || event.sender !== mainWin.webContents) return false;
    await checkForUpdates({ manual: true });
    return true;
});
ipcMain.handle('dwu-setup:info', (event) => (fromSetupWindow(event) ? setupInfo() : null));
ipcMain.handle('dwu-setup:browse', async (event, start) => {
    if (!fromSetupWindow(event)) return null;
    const result = await dialog.showOpenDialog(setupWin, {
        title: 'Choose your Distant Worlds: Universe folder',
        buttonLabel: 'Choose',
        defaultPath: typeof start === 'string' && start !== '' && fs.existsSync(start) ? start : installDir ?? os.homedir(),
        properties: ['openDirectory', 'showHiddenFiles', 'dontAddToRecent'],
    });
    if (result.canceled || result.filePaths.length === 0) return null;
    return result.filePaths[0];
});
ipcMain.handle('dwu-setup:check', (event, dir) => {
    if (!fromSetupWindow(event)) return null;
    return installLib.checkInstallDir(typeof dir === 'string' ? dir.trim() : '');
});
ipcMain.handle('dwu-setup:use', (event, dir) => {
    if (!fromSetupWindow(event)) return null;
    const check = installLib.checkInstallDir(typeof dir === 'string' ? dir.trim() : '');
    if (!check.ok) return check;
    updateConfig({ installDir: check.dir });
    const changed = check.dir !== installDir;
    setInstallDir(check.dir);
    console.log(`[setup] install folder set: ${check.dir}`);
    setupState.finish('ok');
    if (changed && mainWin && !mainWin.isDestroyed()) mainWin.webContents.reload(); // the game reloads its data
    return check;
});
ipcMain.handle('dwu-setup:skip', (event) => {
    if (fromSetupWindow(event)) setupState.finish(setupState.mode === 'first-run' ? 'skip' : 'cancel');
});
ipcMain.handle('dwu-setup:quit', (event) => {
    if (fromSetupWindow(event)) setupState.finish(setupState.mode === 'first-run' ? 'quit' : 'cancel');
});

