// Privileged scheme registration must happen before app ready.
protocol.registerSchemesAsPrivileged([
    {
        scheme: 'dwu',
        privileges: {
            standard: true,
            secure: true,
            supportFetchAPI: true,
            corsEnabled: true,
            stream: true,
        },
    },
]);

if (process.platform === 'win32') app.setAppUserModelId(APP_ID); // taskbar grouping = the installer's shortcuts

// One instance per profile: a second launch focuses the running window (two would fight over the saves' storage).
if (!app.requestSingleInstanceLock()) {
    app.quit();
} else {
    app.on('second-instance', () => {
        const w = setupWin && !setupWin.isDestroyed() ? setupWin : mainWin;
        if (w) {
            if (w.isMinimized()) w.restore();
            w.focus();
        }
    });

    let launching = true;
    app.whenReady().then(async () => {
        // (protocol.handle for dwu:// is registered in the whenReady above.)
        // No menu bar on Windows/Linux (the shell menu pops up on Ctrl+Shift+O); macOS gets the app menu.
        Menu.setApplicationMenu(process.platform === 'darwin' ? buildMacMenu() : null);

        const found = discoverInstallDir();
        if (found.dir) {
            setInstallDir(found.dir);
        } else {
            setInstallDir(null); // our own icon for the setup window
            const result = await openSetupWindow('first-run', found.previous);
            if (result === 'quit') {
                app.quit();
                return;
            }
            if (!installDir) {
                // Player chose to continue without the game files: the game boots with generated fallbacks.
                console.warn('No DW:U install folder configured; running without original assets.');
            }
        }
        createWindow();
        launching = false;

        app.on('activate', () => {
            if (BrowserWindow.getAllWindows().length === 0) createWindow();
        });
    });

    app.on('window-all-closed', () => {
        // The first-run setup window closing must not quit before the main window opens (a 'quit' answer quits above).
        if (launching) return;
        if (process.platform !== 'darwin') app.quit();
    });
}
