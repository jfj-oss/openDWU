/** Windows registry string value via reg.exe (no native modules), or null. */
function readRegistry(key, value) {
    if (process.platform !== 'win32') return null;
    try {
        const out = execFileSync('reg', ['query', key, '/v', value], { encoding: 'utf8', timeout: 3000, windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'] });
        return installLib.parseRegQueryValue(out, value);
    } catch {
        return null; // key or value absent
    }
}

function candidateOpts() {
    return { platform: process.platform, home: os.homedir(), env: process.env, registry: readRegistry };
}

/**
 * Find the DW:U install dir without asking: $DWU_DIR (not saved; for scripts/tests, same variable as
 * `npm run import-assets`) → saved config → the platform's usual places (saved when found).
 * Returns { dir, previous }: previous is a saved folder that is no longer valid (for the setup window's message).
 */
function discoverInstallDir() {
    const envDir = process.env.DWU_DIR;
    if (envDir) {
        if (installLib.checkInstallDirExact(envDir).ok) return { dir: envDir, previous: null };
        console.warn(`DWU_DIR=${envDir} is not a DW:U install folder (needs images/ and races.txt); ignoring it.`);
    }
    const saved = readConfig().installDir;
    if (typeof saved === 'string' && installLib.checkInstallDirExact(saved).ok) return { dir: saved, previous: null };
    const found = installLib.findInstallDir(candidateOpts());
    if (found) {
        updateConfig({ installDir: found });
        return { dir: found, previous: null };
    }
    return { dir: null, previous: typeof saved === 'string' ? saved : null };
}

