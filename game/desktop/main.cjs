/** How this copy was installed, for picking the matching download. */
function installKind() {
    if (process.platform === 'linux' && process.env.APPIMAGE) return 'appimage';
    if (process.platform === 'win32') {
        // electron-builder's NSIS installer puts its uninstaller next to the exe.
        try {
            if (fs.readdirSync(path.dirname(process.execPath)).some((f) => /^Uninstall .*\.exe$/i.test(f))) return 'nsis';
        } catch {
            // fall through
        }
    }
    return 'archive';
}

function updateChecksEnabled() {
    if (process.env.DWU_UPDATE_CHECK === '0') return false;
    if (readConfig().checkForUpdates === false) return false;
    // Unpackaged runs (npm run desktop:dev) never check unless a test points them at a fake API.
    return app.isPackaged || !!process.env.DWU_UPDATE_URL;
}

let updateCheckRunning = false;

/** Check GitHub for a newer release. manual: from the menu (always runs, reports "up to date" and errors). */
async function checkForUpdates({ manual }) {
    if (updateCheckRunning) return;
    if (!manual) {
        if (!updateChecksEnabled()) return;
        if (!updates.isCheckDue(readConfig().lastUpdateCheck, Date.now())) {
            console.log('[update] checked less than a day ago; skipping');
            return;
        }
    }
    updateCheckRunning = true;
    const apiUrl = process.env.DWU_UPDATE_URL || updates.latestReleaseApiUrl(UPDATE_REPO);
    try {
        console.log(`[update] checking ${apiUrl} (running ${APP_VERSION})`);
        const ctrl = new AbortController();
        const timer = setTimeout(() => ctrl.abort(), 15000);
        let res;
        try {
            res = await net.fetch(apiUrl, {
                headers: { Accept: 'application/vnd.github+json', 'User-Agent': `${PRODUCT}/${APP_VERSION} (${process.platform}-${process.arch})`, 'X-GitHub-Api-Version': '2022-11-28' },
                signal: ctrl.signal,
                cache: 'no-store',
            });
        } finally {
            clearTimeout(timer);
        }
        updateConfig({ lastUpdateCheck: Date.now() });
        if (res.status === 404) {
            console.log('[update] no published release yet');
            if (manual) await showMessage({ type: 'info', message: 'No releases published yet', detail: `You are running ${PRODUCT} ${APP_VERSION}.` });
            return;
        }
        if (!res.ok) throw new Error(`GitHub answered HTTP ${res.status}`);
        const release = updates.releaseInfo(await res.json());
        if (!release) throw new Error('unexpected answer from GitHub');
        const newer = updates.compareVersions(release.version, APP_VERSION) > 0;
        console.log(`[update] latest release ${release.version}: ${newer ? 'newer' : 'not newer'}`);
        if (!newer) {
            if (manual) await showMessage({ type: 'info', message: `${PRODUCT} is up to date`, detail: `You are running ${APP_VERSION}, the latest release.` });
            return;
        }
        if (!manual && readConfig().skippedVersion === release.version) {
            console.log(`[update] ${release.version} was skipped by the player`);
            return;
        }
        const download = updates.pickDownload(release, { platform: process.platform, arch: process.arch, kind: installKind() });
        console.log(`[update] offering ${download ? download.name : release.pageUrl ?? '(no download)'}`);
        const notes = updates.notesExcerpt(release.notes);
        const { response } = await showMessage({
            type: 'info',
            buttons: ['Download', 'Later', 'Skip This Version'],
            defaultId: 0,
            cancelId: 1,
            message: `${PRODUCT} ${release.version} is available`,
            detail:
                `You have ${APP_VERSION}. ${download ? `Download opens ${download.name} in your browser` : 'Download opens the release page in your browser'}; ` +
                `install it over this copy (your game folder setting and saves are kept).` +
                (notes ? `\n\n${notes}` : ''),
        });
        if (response === 0) {
            const target = download?.url ?? release.pageUrl;
            if (target && updates.isSafeGithubUrl(target)) await shell.openExternal(target);
        } else if (response === 2) {
            updateConfig({ skippedVersion: release.version });
        }
    } catch (err) {
        console.warn(`[update] check failed: ${err && err.message ? err.message : err}`);
        if (manual) await showMessage({ type: 'warning', message: 'Could not check for updates', detail: String(err && err.message ? err.message : err) });
    } finally {
        updateCheckRunning = false;
    }
}

function showMessage(opts) {
    const parent = mainWin && !mainWin.isDestroyed() ? mainWin : undefined;
    const o = { title: PRODUCT, buttons: ['OK'], ...opts };
    return parent ? dialog.showMessageBox(parent, o) : dialog.showMessageBox(o);
}

