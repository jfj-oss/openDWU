let mainWin = null;

function toggleFullscreen(win) {
    win.setFullScreen(!win.isFullScreen());
}

function createWindow() {
    const win = new BrowserWindow({
        width: 1600,
        height: 900,
        minWidth: 1280,
        minHeight: 720,
        title: 'Distant Worlds: Universe',
        backgroundColor: '#000',
        show: false,
        // Window icon on Linux/Windows (macOS ignores `icon`; the dock icon is
        // set via app.dock.setIcon in setInstallDir). Empty image = Electron default.
        icon: appIcon.isEmpty() ? undefined : appIcon,
        webPreferences: {
            contextIsolation: true,
            nodeIntegration: false,
            sandbox: true,
            preload: path.join(__dirname, 'gamePreload.cjs'),
        },
    });
    mainWin = win;
    win.on('closed', () => {
        if (mainWin === win) mainWin = null;
    });

    // The game page died (out of memory, a crash, killed): instead of leaving a black window, log why and offer a
    // reload. The last autosave or manual save is where to continue from.
    // The page's last warnings / errors and its memory, kept for the crash log (a crash leaves no other trace).
    const recentConsole = [];
    let lastMemory = '';
    win.webContents.on('console-message', (event, ...legacy) => {
        // Electron 44: event.level is 'warning' / 'error' / ...; older: (event, level, message).
        const level = event.level ?? (['verbose', 'info', 'warning', 'error'][legacy[0]] || String(legacy[0]));
        const message = event.message ?? legacy[1];
        if (level !== 'warning' && level !== 'error') return;
        const entry = `${new Date().toISOString()} [${level}] ${String(message).slice(0, 500)}`;
        recentConsole.push(entry);
        if (recentConsole.length > 40) recentConsole.shift();
        // The sim worker stopping (it crashed, ran out of memory — V8 kills only its isolate, the page lives on and
        // reports it after its silence watchdog — or stopped answering) goes to the crash log at once, with the memory:
        // the page may well die of the same cause minutes later, or the player quits from the restart prompt.
        if (level === 'error' && /sim worker: STOPPED|Autosave failed/.test(String(message))) {
            try {
                fs.appendFileSync(path.join(app.getPath('userData'), 'crash-log.txt'), `${entry} version=${APP_VERSION}\n` + (lastMemory !== '' ? `  last memory sample: ${lastMemory}\n` : ''));
            } catch {
                /* best effort */
            }
        }
    });
    const memoryTimer = setInterval(() => {
        try {
            const pid = win.webContents.getOSProcessId();
            const m = app.getAppMetrics().find((x) => x.pid === pid);
            if (m) lastMemory = `${new Date().toISOString()} page working set ${(m.memory.workingSetSize / 1024 / 1024).toFixed(2)} GB, peak ${(m.memory.peakWorkingSetSize / 1024 / 1024).toFixed(2)} GB`;
        } catch {
            /* the page is gone */
        }
    }, 15000);
    win.on('closed', () => clearInterval(memoryTimer));
    win.webContents.on('render-process-gone', async (_event, details) => {
        const line =
            `${new Date().toISOString()} render-process-gone reason=${details.reason} exitCode=${details.exitCode} version=${APP_VERSION}\n` +
            (lastMemory !== '' ? `  last memory sample: ${lastMemory}\n` : '') +
            (recentConsole.length > 0 ? `  last page warnings / errors:\n${recentConsole.map((l) => `    ${l}`).join('\n')}\n` : '');
        recentConsole.length = 0;
        console.error(`[crash] ${line.trim()}`);
        try {
            fs.appendFileSync(path.join(app.getPath('userData'), 'crash-log.txt'), line);
        } catch {
            /* best effort */
        }
        if (win.isDestroyed()) return;
        const oom = details.reason === 'oom';
        const { response } = await showMessage({
            type: 'error',
            buttons: ['Reload', 'Quit'],
            defaultId: 0,
            cancelId: 1,
            message: oom ? 'The game ran out of memory' : 'The game stopped unexpectedly',
            detail:
                `Reason: ${details.reason} (exit code ${details.exitCode}). ` +
                'Reload returns to the main menu; load your last save or autosave to continue. ' +
                `Details are in ${path.join(app.getPath('userData'), 'crash-log.txt')}.`,
        });
        if (response === 0 && !win.isDestroyed()) win.reload();
        else app.quit();
    });

    win.once('ready-to-show', () => {
        win.show();
        // The daily update check, once the game is up (and off the startup path).
        setTimeout(() => checkForUpdates({ manual: false }), 8000);
    });

    // F11 / Ctrl/Cmd+F toggles fullscreen; Ctrl+Shift+O opens the shell menu on Windows/Linux (no menu bar there).
    win.webContents.on('before-input-event', (event, input) => {
        if (input.type !== 'keyDown') return;
        const isF11 = input.key === 'F11';
        const isCtrlCmdF = input.key === 'f' && (input.controlKey || input.metaKey);
        if (isF11 || isCtrlCmdF) {
            toggleFullscreen(win);
        }
        if (process.platform !== 'darwin' && input.control && input.shift && !input.alt && !input.meta && input.key.toLowerCase() === 'o') {
            event.preventDefault(); // the game never sees it
            popupShellMenu(win);
        }
    });

    // Links the game opens (if any) go to the browser; the window itself only ever shows dwu://app/.
    win.webContents.setWindowOpenHandler(({ url }) => {
        if (/^https:\/\//.test(url)) shell.openExternal(url);
        return { action: 'deny' };
    });

    win.loadURL('dwu://app/index.html');
}

