/** Show the setup window. mode 'first-run' resolves 'ok' | 'skip' | 'quit'; mode 'change' resolves 'ok' | 'cancel'. */
function openSetupWindow(mode, previous = null) {
    if (setupWin && !setupWin.isDestroyed()) {
        setupWin.focus();
        return setupState.promise;
    }
    const parent = mode === 'change' ? mainWin ?? undefined : undefined;
    setupWin = new BrowserWindow({
        width: 760,
        height: process.platform === 'darwin' ? 720 : 680,
        minWidth: 560,
        minHeight: 520,
        title: `${PRODUCT} — Distant Worlds: Universe folder`,
        backgroundColor: '#0b1220',
        show: false,
        parent,
        modal: mode === 'change' && process.platform !== 'linux', // Linux WMs handle modal children poorly
        icon: appIcon.isEmpty() ? undefined : appIcon,
        autoHideMenuBar: true,
        webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true, preload: path.join(__dirname, 'setupPreload.cjs') },
    });
    setupWin.setMenuBarVisibility(false);
    const win = setupWin;
    let resolveFn;
    const promise = new Promise((r) => (resolveFn = r));
    const state = { mode, previous, promise, done: false };
    state.finish = (result) => {
        if (state.done) return;
        state.done = true;
        resolveFn(result);
        if (!win.isDestroyed()) win.close();
    };
    setupState = state;
    // Closing the window = Quit (first run) / Cancel (change).
    win.on('closed', () => {
        state.finish(mode === 'first-run' ? 'quit' : 'cancel');
        if (setupWin === win) setupWin = null;
    });
    // Links in the page open in the browser, never in the app.
    win.webContents.setWindowOpenHandler(({ url }) => {
        if (updates.isSafeGithubUrl(url) || /^https:\/\/(store\.steampowered\.com|getwhisky\.app|www\.codeweavers\.com)\//.test(url)) shell.openExternal(url);
        return { action: 'deny' };
    });
    win.webContents.on('will-navigate', (e) => e.preventDefault());
    win.once('ready-to-show', () => win.show());
    win.loadFile(path.join(__dirname, 'setup.html'));
    return promise;
}

