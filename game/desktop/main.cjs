/** Built at launch / on folder change: the JSON bodies of asset-manifest.json and theme-manifest/*. */
let assetManifestBody = '{}';
const themeBodies = new Map(); // name ('index.json' | '<set>.json') -> body | null (404)

function setInstallDir(dir) {
    installDir = dir;
    resolver.clearCache();
    themeBodies.clear();
    const t0 = Date.now();
    assetManifestBody = dir ? JSON.stringify(buildAssetManifest(dir)) : '{}';
    if (dir) {
        const themes = themeIndex.listThemes(dir);
        themeBodies.set('index.json', JSON.stringify(themes));
        for (const t of themes) {
            const idx = themeIndex.buildThemeIndex(dir, t);
            themeBodies.set(`${t}.json`, idx === null ? null : JSON.stringify(idx));
        }
        console.log(`[install] ${dir}: asset manifest ${Math.round(assetManifestBody.length / 1024)} KB, ${themes.length} theme(s) in ${Date.now() - t0} ms`);
    }
    appIcon = makeAppIcon(dir);
    for (const win of BrowserWindow.getAllWindows()) if (!appIcon.isEmpty()) win.setIcon?.(appIcon);
    if (process.platform === 'darwin' && !appIcon.isEmpty()) app.dock?.setIcon(appIcon);
}

/** theme-manifest/<name>: from the table built in setInstallDir; a theme added since is indexed on first request. */
function themeBody(name) {
    if (!installDir) return name === 'index.json' ? '[]' : null;
    if (themeBodies.has(name)) return themeBodies.get(name);
    let body = null;
    if (name.endsWith('.json')) {
        const idx = themeIndex.buildThemeIndex(installDir, name.slice(0, -'.json'.length));
        if (idx !== null) body = JSON.stringify(idx);
    }
    themeBodies.set(name, body);
    return body;
}

