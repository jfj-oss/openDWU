function createWindow() {
    const win = new BrowserWindow({
        width: 1600,
        height: 900,
        minWidth: 1280,
        minHeight: 720,
        title: 'Distant Worlds: Universe',
        backgroundColor: '#000',
        show: false,
        // Window icon on Linux/Windows (macOS ignores `icon`; the dock icon is
        // set via app.dock.setIcon in setInstallDir). Empty image = Electron default.
        icon: appIcon.isEmpty() ? undefined : appIcon,
        webPreferences: {
            contextIsolation: true,
            nodeIntegration: false,
            sandbox: true,
            preload: path.join(__dirname, 'gamePreload.cjs'),
            // DWU_DEV_HOOKS=1: the multiplayer debug hooks and test switches (src/ui/multiplayer/devHooks.ts) for scripts.
            ...(process.env.DWU_DEV_HOOKS === '1' ? { additionalArguments: ['--dwu-dev-hooks'] } : {}),
        },
    });
    mainWin = win;
    const onFullscreenChange = () => {
        const on = win.isFullScreen();
        if (readConfig().fullscreen !== on) updateConfig({ fullscreen: on });
        if (!win.webContents.isDestroyed()) win.webContents.send('dwu:fullscreen-changed', on);
    };
    win.on('enter-full-screen', onFullscreenChange);
    win.on('leave-full-screen', onFullscreenChange);
    win.on('closed', () => {
        if (mainWin === win) mainWin = null;
    });

    // The GPU process died (a driver reset, out of GPU memory): logged with the memory sample; the page's context-loss
    // recovery (contextLoss.ts) brings the map back.
    const onChildGone = (_event, details) => {
        if (!details || details.type !== 'GPU') return;
        appendCrashLog(`${new Date().toISOString()} gpu-process-gone reason=${details.reason} exitCode=${details.exitCode} version=${APP_VERSION}\n` + (gpuInfoText ? `  ${gpuInfoText}\n` : '') + (lastMemory !== '' ? `  last memory sample: ${lastMemory}\n` : ''));
    };
    app.on('child-process-gone', onChildGone);
    win.on('closed', () => app.removeListener('child-process-gone', onChildGone));
    // The game page died (out of memory, a crash, killed): instead of leaving a black window, log why and offer a
    // reload. The last autosave or manual save is where to continue from.
    // The page's last warnings / errors and its memory, kept for the crash log (a crash leaves no other trace).
    const recentConsole = [];
    let lastMemory = '';
    win.webContents.on('console-message', (event, ...legacy) => {
        // Electron 44: event.level is 'warning' / 'error' / ...; older: (event, level, message).
        const level = event.level ?? (['verbose', 'info', 'warning', 'error'][legacy[0]] || String(legacy[0]));
        const message = event.message ?? legacy[1];
        if (level !== 'warning' && level !== 'error') return;
        const entry = `${new Date().toISOString()} [${level}] ${String(message).slice(0, 500)}`;
        recentConsole.push(entry);
        if (recentConsole.length > 40) recentConsole.shift();
        // The sim worker stopping (it crashed, ran out of memory — V8 kills only its isolate, the page lives on and
        // reports it after its silence watchdog — or stopped answering) goes to the crash log at once, with the memory:
        // the page may well die of the same cause minutes later, or the player quits from the restart prompt. A save
        // that does not load goes there too (its reason: the panel shows only the first line).
        // WebGL context loss / restore (contextLoss.ts) too: a blank map after a GPU reset shows in the player's log.
        if (/WebGL context (lost|still lost|restored)|rebuilding the view|view rebuild after a GPU reset/.test(String(message))) {
            appendCrashLog(`${entry} version=${APP_VERSION}\n` + (lastMemory !== '' ? `  last memory sample: ${lastMemory}\n` : ''));
        } else if (level === 'error' && /sim worker: STOPPED|Autosave failed|Failed to load save|Failed to read save file/.test(String(message))) {
            appendCrashLog(`${entry} version=${APP_VERSION}\n` + (lastMemory !== '' ? `  last memory sample: ${lastMemory}\n` : ''));
        }
    });
    const memoryTimer = setInterval(() => {
        try {
            const pid = win.webContents.getOSProcessId();
            const m = app.getAppMetrics().find((x) => x.pid === pid);
            if (m) lastMemory = `${new Date().toISOString()} page working set ${(m.memory.workingSetSize / 1024 / 1024).toFixed(2)} GB, peak ${(m.memory.peakWorkingSetSize / 1024 / 1024).toFixed(2)} GB`;
            // The sim process (simProcess.cjs) beside it: the page's crash log names both.
            for (const sim of simProcesses.list()) {
                if (sim.owner === win.webContents && sim.memory) lastMemory += `; sim process working set ${sim.memory.workingSetGB.toFixed(2)} GB, peak ${sim.memory.peakGB.toFixed(2)} GB`;
            }
        } catch {
            /* the page is gone */
        }
    }, 15000);
    win.on('closed', () => clearInterval(memoryTimer));
    win.webContents.on('render-process-gone', async (_event, details) => {
        const line =
            `${new Date().toISOString()} render-process-gone reason=${details.reason} exitCode=${details.exitCode} version=${APP_VERSION}\n` +
            (lastMemory !== '' ? `  last memory sample: ${lastMemory}\n` : '') +
            (recentConsole.length > 0 ? `  last page warnings / errors:\n${recentConsole.map((l) => `    ${l}`).join('\n')}\n` : '');
        recentConsole.length = 0;
        console.error(`[crash] ${line.trim()}`);
        appendCrashLog(line);
        if (win.isDestroyed()) return;
        const oom = details.reason === 'oom';
        const { response } = await showMessage({
            type: 'error',
            buttons: ['Reload', 'Quit'],
            defaultId: 0,
            cancelId: 1,
            message: oom ? 'The game ran out of memory' : 'The game stopped unexpectedly',
            detail:
                `Reason: ${details.reason} (exit code ${details.exitCode}). ` +
                'Reload returns to the main menu; load your last save or autosave to continue. ' +
                `Details are in ${path.join(app.getPath('userData'), 'crash-log.txt')}.`,
        });
        if (response === 0 && !win.isDestroyed()) win.reload();
        else app.quit();
    });

    // DWU_SENTRY_TEST=1 (with DWU_SENTRY=1): one deliberate error in the main process and one in the page, to check
    // that reports arrive. Inactive without the variable.
    if (process.env.DWU_SENTRY_TEST === '1') {
        win.webContents.once('did-finish-load', () => {
            setTimeout(() => {
                win.webContents.executeJavaScript("setTimeout(() => { throw new Error('DWU_SENTRY_TEST renderer error'); }, 0)").catch(() => {});
                setTimeout(() => {
                    throw new Error('DWU_SENTRY_TEST main error');
                }, 1500);
            }, 3000);
        });
    }
    win.once('ready-to-show', () => {
        win.show();
        if (readConfig().fullscreen === true) setFullscreen(win, true);
        // Which GPU path the app got (the page adds its renderer through dwu:report-renderer).
        try {
            console.log(displayMode.gpuLogLine(app.getGPUFeatureStatus(), null));
        } catch {
            /* not available */
        }
        app.getGPUInfo('complete')
            .then((info) => {
                gpuInfoText = displayMode.gpuInfoLine(info);
                crashReport.setTags({ gpu_info: gpuInfoText.slice(0, 200) });
                console.log(gpuInfoText);
            })
            .catch(() => {});
        // The update check on every launch, once the game is up (and off the startup path).
        {
            const cfg = readConfig();
            if (cfg.installedUpdateTo) {
                if (cfg.installedUpdateTo === APP_VERSION) analytics.track('update_installed', { from: cfg.installedUpdateFrom, to: APP_VERSION });
                updateConfig({ installedUpdateFrom: undefined, installedUpdateTo: undefined });
            }
        }
        selfUpdate.cleanupStaged(UPDATES_DIR(), APP_VERSION, updates.compareVersions);
        setTimeout(() => checkForUpdates({ manual: false }), 8000);
    });

    // F11 / Alt+Enter / Ctrl/Cmd+F toggles fullscreen; Ctrl+Shift+O opens the shell menu on Windows/Linux (no menu bar there).
    win.webContents.on('before-input-event', (event, input) => {
        if (input.type !== 'keyDown') return;
        // F11 still reaches the page as well (the original's Ships and Bases key); Alt+Enter / Ctrl+F do not.
        if (displayMode.isFullscreenToggle(input, process.platform)) {
            if (input.key !== 'F11') event.preventDefault();
            toggleFullscreen(win);
        }
        if (process.platform !== 'darwin' && input.control && input.shift && !input.alt && !input.meta && input.key.toLowerCase() === 'o') {
            event.preventDefault(); // the game never sees it
            popupShellMenu(win);
        }
    });

    // Links the game opens (if any) go to the browser; the window itself only ever shows dwu://app/.
    win.webContents.setWindowOpenHandler(({ url }) => {
        if (/^https:\/\//.test(url)) shell.openExternal(url);
        return { action: 'deny' };
    });

    win.loadURL('dwu://app/index.html');
}

